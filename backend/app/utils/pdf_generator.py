def _qr_drawing(data: str, size: float = 26*mm) -> Drawing:
    qr = QrCodeWidget(data)
    b = qr.getBounds()
    w, h = b[2]-b[0], b[3]-b[1]
    d = Drawing(size, size, transform=[size/w, 0, 0, size/h, 0, 0])
    d.add(qr)
    return d


