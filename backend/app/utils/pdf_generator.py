def _fmt(v) -> str:
    """Indian numbering, non-breaking: ₹17,84,963.00"""
    v = float(v or 0)
    neg = v < 0
    v = abs(v)
    whole, _, frac = f"{v:,.2f}".partition(".")
    whole = whole.replace(",", "")
    if len(whole) > 3:
        last3, rest = whole[-3:], whole[:-3]
        groups = []
        while len(rest) > 2:
            groups.insert(0, rest[-2:])
            rest = rest[:-2]
        if rest:
            groups.insert(0, rest)
        whole = ",".join(groups) + "," + last3
    return f"{'-' if neg else ''}₹{whole}.{frac}"

